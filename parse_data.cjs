const lines = rawData.split('\n');
const items = [];
let currentItem = null;
let currentTheme = '';
let currentThemeNumber = 0;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i].trim();
  
  if (line.match(/Tema \d+:/)) {
    // New theme
    const match = line.match(/Tema (\d+): (.*)/);
    if (match) {
      currentThemeNumber = parseInt(match[1]);
      currentTheme = match[2].trim();
    }
  } else if (line.match(/^Dia \d+:/)) {
    // New day
    if (currentItem) {
      items.push(currentItem);
    }
    const match = line.match(/^Dia (\d+): (.*)/);
    const dayNum = match[1];
    const title = match[2].trim();
    
    currentItem = {
      id: `t${currentThemeNumber}d${dayNum}`,
      theme: currentTheme,
      title: title,
      description: "",
      beautifulWord: "",
      content: ""
    };
  } else if (line.startsWith('📖 Versículo Base:')) {
    if (currentItem) {
      currentItem.beautifulWord = line.replace('📖 Versículo Base:', '').trim();
    }
  } else if (line.startsWith('🙏 Oração:')) {
    if (currentItem) {
      currentItem.content += `\n\n**Oração:**\n${line.replace('🙏 Oração:', '').trim()}`;
    }
  } else if (line.length > 0 && currentItem) {
    if (currentItem.content.length > 0) {
      currentItem.content += '\n\n';
    }
    currentItem.content += line;
  }
}

if (currentItem) {
  items.push(currentItem);
}

// Post-process descriptions
items.forEach(item => {
  const words = item.content.split(' ');
  let desc = words.slice(0, 10).join(' ');
  if (words.length > 10) desc += '...';
  item.description = desc.replace(/\n/g, ' ');
});

